"""
Django settings for the TechnoLearn backend.

Configuration is driven by environment variables with development-friendly
defaults so the project runs out of the box. Sensitive values (secret key,
debug flag, allowed hosts) are read from the environment, and a local `.env`
file in the backend directory is loaded automatically when present.
"""
import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def _load_env_file() -> None:
    """Load a local `.env` file into os.environ without extra dependencies."""
    env_path = BASE_DIR / ".env"
    if not env_path.exists():
        return
    for raw_line in env_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        # Do not override values already exported in the real environment.
        os.environ.setdefault(key, value)


_load_env_file()

